async function main() {
  console.log("\n🚀 開始發布 10 篇 TA 爆款文章到資料庫...\n");

  // 1. 取得現有分類映射
  const categories = await prisma.category.findMany();
  const categoryMap = {};
  for (const cat of categories) {
    categoryMap[cat.slug] = cat.id;
  }

  // 2. 依序 upsert 文章
  let count = 0;
  for (const item of ARTICLES) {
    const categoryId = categoryMap[item.categorySlug];
    if (!categoryId) {
      console.warn(`⚠️ 找不到分類 slug: ${item.categorySlug}，跳過文章: ${item.title}`);
      continue;
    }

    const post = await prisma.post.upsert({
      where: { slug: item.slug },
      update: {
        title: item.title,
        content: item.content.trim(),
        excerpt: item.excerpt,
        coverImage: item.coverImage,
        tags: item.tags,
        categoryId: categoryId,
        published: true,
        updatedAt: new Date(),
      },
      create: {
        title: item.title,
        slug: item.slug,
        content: item.content.trim(),
        excerpt: item.excerpt,
        coverImage: item.coverImage,
        tags: item.tags,
        categoryId: categoryId,
        published: true,
      },
    });

    count++;
    console.log(`[${count}/10] ✅ 成功發布: ${post.title}`);
  }

  console.log(`\n🎉 全部 10 篇高品質文章發布完成！共上線 ${count} 篇文章。`);
  console.log("👉 前往線上部落格查驗: https://tarot-divination.zipffdigital.com/articles");
  console.log("👉 前往管理後台查驗: https://tarot-divination.zipffdigital.com/admin/posts\n");
}

main()
  .catch((e) => {
    console.error("❌ 發布失敗:", e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
